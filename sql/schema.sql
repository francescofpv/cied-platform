-- =====================================================================
-- RICERCA PAZIENTI (vault): testo libero + filtri produttore, modello, gruppo, NAO
-- =====================================================================
-- Testo di ricerca di un paziente: cognome (anche senza spazi: "De Luca" -> "deluca"),
-- nome, codice paziente, anno di nascita, ID esterni e, per ogni dispositivo,
-- produttore (codice e nome), modello (anche senza spazi) e seriale.
-- Inizia con uno spazio: ogni parola cercata deve trovare l'INIZIO di una parola
-- (LIKE '% parola%'), così "III" trova "BIOMONITOR III" ma non "BIOMONITOR IV".
CREATE OR REPLACE FUNCTION vault.build_search_text(p_no bigint, p_family text, p_given text, p_birth date)
RETURNS text LANGUAGE sql STABLE AS $$
    SELECT ' ' || concat_ws(' ',
        vault.norm(p_family), replace(vault.norm(p_family), ' ', ''),
        vault.norm(regexp_replace(p_family, '[''’`]', ' ', 'g')),      -- "D'Amico" trovabile anche come "amico"
        vault.norm(p_given),
        p_no::text, to_char(p_birth, 'YYYY'),
        (SELECT string_agg(concat_ws(' ', vault.norm(di.manufacturer), vault.norm(m.name),
                                     vault.norm(di.model), replace(vault.norm(di.model), ' ', ''),
                                     vault.norm(di.serial_number), replace(vault.norm(di.serial_number), ' ', '')),
                           ' ')
           FROM vault.device_identity di LEFT JOIN cied.manufacturer m ON m.code = di.manufacturer
          WHERE di.patient_no = p_no),
        (SELECT string_agg(vault.norm(pi.value), ' ') FROM vault.patient_identifier pi WHERE pi.patient_no = p_no)
    ) || ' '
$$;

CREATE OR REPLACE FUNCTION vault.trg_patient_search() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    NEW.search_text := vault.build_search_text(NEW.patient_no, NEW.name_family, NEW.name_given, NEW.birth_date);
    RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS trg_patient_search ON vault.patient;
CREATE TRIGGER trg_patient_search
    BEFORE INSERT OR UPDATE OF name_family, name_given, birth_date ON vault.patient
    FOR EACH ROW EXECUTE FUNCTION vault.trg_patient_search();

-- Quando cambiano dispositivi o ID esterni si ricalcola il testo dei pazienti coinvolti
CREATE OR REPLACE FUNCTION vault.trg_refresh_search() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    UPDATE vault.patient p
       SET search_text = vault.build_search_text(p.patient_no, p.name_family, p.name_given, p.birth_date)
     WHERE p.patient_no IN (CASE WHEN TG_OP <> 'INSERT' THEN OLD.patient_no END,
                            CASE WHEN TG_OP <> 'DELETE' THEN NEW.patient_no END);
    RETURN NULL;
END $$;

DROP TRIGGER IF EXISTS trg_device_search ON vault.device_identity;
CREATE TRIGGER trg_device_search
    AFTER INSERT OR UPDATE OF patient_no, manufacturer, model, serial_number OR DELETE ON vault.device_identity
    FOR EACH ROW EXECUTE FUNCTION vault.trg_refresh_search();
DROP TRIGGER IF EXISTS trg_identifier_search ON vault.patient_identifier;
CREATE TRIGGER trg_identifier_search
    AFTER INSERT OR UPDATE OF patient_no, value OR DELETE ON vault.patient_identifier
    FOR EACH ROW EXECUTE FUNCTION vault.trg_refresh_search();

-- Indice trigram: rende veloci le ricerche LIKE '% parola%' anche con decine di migliaia di pazienti
CREATE INDEX IF NOT EXISTS ix_patient_search ON vault.patient USING gin (search_text public.gin_trgm_ops);

-- Ricerca. Tutti i parametri sono facoltativi:
--   p_query        testo libero ("rossi", "Biotronik III", "biomonitor iv 12345678", "100001")
--   p_manufacturer codice produttore (BIO, ...)         p_model  modello esatto
--   p_group_pk     gruppo di pazienti                   p_nao    'SI' | 'NO' | 'NON_INDICATO'
-- Risultati ordinati per pertinenza (con testo) o per cognome; "total" = risultati complessivi.
DROP FUNCTION IF EXISTS vault.search_patients(text, text, text, integer, text, integer, integer);
CREATE FUNCTION vault.search_patients(
    p_query text DEFAULT NULL, p_manufacturer text DEFAULT NULL, p_model text DEFAULT NULL,
    p_group_pk integer DEFAULT NULL, p_nao text DEFAULT NULL,
    p_limit integer DEFAULT 50, p_offset integer DEFAULT 0)
RETURNS TABLE (patient_no bigint, name_family text, name_given text, birth_date date, sex text,
               nao_therapy boolean, devices text, groups text, score real, total bigint)
LANGUAGE plpgsql STABLE SECURITY DEFINER
SET search_path = pg_catalog, public, pg_temp AS $$
DECLARE
    qn   text := vault.norm(p_query);
    toks text[] := CASE WHEN vault.norm(p_query) = '' THEN '{}'::text[]
                        ELSE regexp_split_to_array(vault.norm(p_query), ' ') END;
    cond text := '';
    i    integer;
BEGIN
    IF p_nao IS NOT NULL AND p_nao NOT IN ('SI', 'NO', 'NON_INDICATO') THEN
        RAISE EXCEPTION 'p_nao deve essere SI, NO o NON_INDICATO';
    END IF;
    -- Si aggiungono solo le condizioni dei filtri impostati, così il planner sceglie
    -- il piano migliore: una LIKE per parola (indice trigram), semi-join per i filtri.
    FOR i IN 1 .. coalesce(array_length(toks, 1), 0) LOOP
        cond := cond || format(' AND p.search_text LIKE (''%% '' || $1[%s] || ''%%'')', i);
    END LOOP;
    IF p_manufacturer IS NOT NULL OR p_model IS NOT NULL THEN
        cond := cond || ' AND p.patient_no IN (SELECT d.patient_no FROM vault.device_identity d WHERE true'
                     || CASE WHEN p_manufacturer IS NOT NULL THEN ' AND d.manufacturer = $3' ELSE '' END
                     || CASE WHEN p_model IS NOT NULL THEN ' AND d.model = $4' ELSE '' END || ')';
    END IF;
    IF p_group_pk IS NOT NULL THEN
        cond := cond || ' AND cp.patient_pk IN (SELECT gm.patient_pk FROM cied.patient_group_member gm'
                     || ' WHERE gm.group_pk = $5)';
    END IF;
    cond := cond || CASE p_nao WHEN 'SI' THEN ' AND cp.nao_therapy' WHEN 'NO' THEN ' AND NOT cp.nao_therapy'
                               WHEN 'NON_INDICATO' THEN ' AND cp.nao_therapy IS NULL' ELSE '' END;

    -- 1) si sceglie la pagina (solo chiavi e punteggio)  2) si completano solo quelle righe
    RETURN QUERY EXECUTE format($q$
        WITH hits AS (
            SELECT p.patient_no, cp.patient_pk,
                   CASE WHEN $2 = '' THEN 0::real ELSE public.similarity(p.search_text, $2) END AS score,
                   count(*) OVER () AS total
              FROM vault.patient p
              JOIN cied.patient cp ON cp.patient_pseudo = p.patient_pseudo
             WHERE true %s
             ORDER BY 3 DESC, p.name_family, p.name_given, p.patient_no
             LIMIT $6 OFFSET $7)
        SELECT p.patient_no, p.name_family, p.name_given, p.birth_date, p.sex, cp.nao_therapy,
               (SELECT string_agg(coalesce(m.name, di.manufacturer) || ' ' || di.model || ' (' || di.serial_number || ')',
                                  ', ' ORDER BY di.first_seen)
                  FROM vault.device_identity di LEFT JOIN cied.manufacturer m ON m.code = di.manufacturer
                 WHERE di.patient_no = p.patient_no),
               (SELECT string_agg(g.name, ', ' ORDER BY g.name)
                  FROM cied.patient_group_member gm JOIN cied.patient_group g USING (group_pk)
                 WHERE gm.patient_pk = h.patient_pk),
               h.score, h.total
          FROM hits h
          JOIN vault.patient p USING (patient_no)
          JOIN cied.patient cp ON cp.patient_pk = h.patient_pk
         ORDER BY h.score DESC, p.name_family, p.name_given, p.patient_no $q$, cond)
    USING toks, qn, p_manufacturer, p_model, p_group_pk, least(greatest(p_limit, 1), 500),
          greatest(p_offset, 0);
END $$;

-- Valori per le tendine dei filtri:
--   kind = 'manufacturer' (value = codice, label = nome), 'model' (parent = codice produttore),
--   'group' (value = group_pk). n = numero di pazienti.
CREATE OR REPLACE FUNCTION vault.search_options()
RETURNS TABLE (kind text, value text, label text, parent text, n bigint)
LANGUAGE sql STABLE SECURITY DEFINER
SET search_path = pg_catalog, pg_temp AS $$
    WITH pm AS (   -- coppie (produttore, modello, paziente) distinte
        SELECT DISTINCT di.manufacturer, di.model, di.patient_no FROM vault.device_identity di
    ), pmf AS (
        SELECT DISTINCT manufacturer, patient_no FROM pm
    )
    SELECT 'manufacturer', f.manufacturer, coalesce(m.name, f.manufacturer), NULL::text, f.n
      FROM (SELECT manufacturer, count(patient_no) AS n FROM pmf GROUP BY manufacturer) f
      LEFT JOIN cied.manufacturer m ON m.code = f.manufacturer
    UNION ALL
    SELECT 'model', model, model, manufacturer, count(patient_no)
      FROM pm WHERE model <> '' GROUP BY manufacturer, model
    UNION ALL
    SELECT 'group', g.group_pk::text, g.name, NULL, count(gm.patient_pk)
      FROM cied.patient_group g LEFT JOIN cied.patient_group_member gm USING (group_pk)
     GROUP BY g.group_pk, g.name
    ORDER BY 1, 4 NULLS FIRST, 3
$$;

-- =====================================================================
-- RIEPILOGO CLINICO IDENTIFICATO (solo per cied_clinician, con log)
-- =====================================================================
DROP FUNCTION IF EXISTS vault.clinical_summary();
CREATE FUNCTION vault.clinical_summary()
RETURNS TABLE (
    patient_no         bigint,
    name_family        text,
    name_given         text,
    birth_date         date,
    nao_therapy        boolean,
    device_type        text,
    model              text,
    implant_date       date,
    explant_date       date,
    pregresse          text,
    indicazioni        text,
    last_session       timestamptz,
    at_burden_pct      double precision,
    v_rate_mean_bpm    double precision,
    open_notifications bigint,
    top_priority       text,
    hmsc_link          text,
    clinical_record    text                   -- 'completa' | 'da completare'
)
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = pg_catalog, pg_temp AS $$
DECLARE n integer;
BEGIN
    RETURN QUERY
    WITH last_sess AS (
        SELECT DISTINCT ON (s.device_pk) s.device_pk, s.session_pk, s.session_dtm
        FROM cied.session s ORDER BY s.device_pk, s.session_dtm DESC
    )
    SELECT vp.patient_no, vp.name_family, vp.name_given, vp.birth_date, cp.nao_therapy,
           d.device_type, d.model,
           COALESCE(vi.implant_date, d.implant_dt), vi.explant_date,
           vi.pregresse, vi.indicazioni,
           ls.session_dtm,
           (SELECT o.value_num FROM cied.observation o
             WHERE o.session_pk = ls.session_pk AND o.term = 'MDC_IDC_STAT_AT_BURDEN_PERCENT' LIMIT 1),
           (SELECT o.value_num FROM cied.observation o
             WHERE o.session_pk = ls.session_pk AND o.term = 'MDC_IDC_STAT_HEART_RATE_VENTRICULAR_MEAN' LIMIT 1),
           (SELECT count(*) FROM cied.notification nt
             WHERE nt.device_pk = d.device_pk AND nt.status = 'UNACKNOWLEDGED'),
           (SELECT nt.priority FROM cied.notification nt
             WHERE nt.device_pk = d.device_pk AND nt.status = 'UNACKNOWLEDGED'
             ORDER BY CASE nt.priority WHEN 'HIGH' THEN 1 WHEN 'MEDIUM' THEN 2 ELSE 3 END LIMIT 1),
           di.hmsc_link,
           CASE WHEN vi.implant_pk IS NULL THEN 'da completare' ELSE 'completa' END
    FROM cied.device d
    LEFT JOIN cied.patient cp       ON cp.patient_pk = d.patient_pk
    LEFT JOIN vault.patient vp      ON vp.patient_pseudo = cp.patient_pseudo
    LEFT JOIN vault.device_identity di ON di.device_pseudo = d.device_pseudo
    LEFT JOIN cied.v_implant vi     ON vi.device_pseudo = d.device_pseudo
    LEFT JOIN last_sess ls          ON ls.device_pk = d.device_pk
    ORDER BY 15 DESC, vp.name_family, vp.name_given;

    GET DIAGNOSTICS n = ROW_COUNT;
    INSERT INTO vault.access_log (db_user, action, rows_returned)
    VALUES (session_user, 'clinical_summary', n);
END $$;

