-- ---------------------------------------------------------------------
-- Regole che coinvolgono più tabelle: verificate al COMMIT (trigger differiti),
-- così impianto e patologie si inseriscono insieme nella stessa transazione.
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION cied.check_implant() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    pk  bigint := COALESCE(NEW.implant_pk, OLD.implant_pk);
    r   cied.implant;
    dev cied.device;
    n_none integer;
    n_preg integer;
BEGIN
    SELECT * INTO r FROM cied.implant WHERE implant_pk = pk;
    IF NOT FOUND THEN RETURN NULL; END IF;            -- impianto cancellato
    SELECT * INTO dev FROM cied.device WHERE device_pk = r.device_pk;

    SELECT count(*), count(*) FILTER (WHERE c.coding_system = 'LOCAL' AND c.code = 'NONE')
      INTO n_preg, n_none
      FROM cied.implant_condition ic JOIN cied.condition c USING (condition_pk)
     WHERE ic.implant_pk = pk AND ic.role = 'PREGRESSA';
    IF n_preg = 0 THEN
        RAISE EXCEPTION 'Impianto %: indicare almeno una patologia pregressa (LOCAL:NONE se assenti)', pk;
    END IF;
    IF n_none > 0 AND n_preg > 1 THEN
        RAISE EXCEPTION 'Impianto %: "nessuna patologia pregressa" non può essere combinata con altre', pk;
    END IF;

    IF NOT EXISTS (SELECT 1 FROM cied.implant_condition WHERE implant_pk = pk AND role = 'INDICAZIONE') THEN
        RAISE EXCEPTION 'Impianto %: indicare la motivazione dell''impianto (almeno una patologia/evento)', pk;
    END IF;

    IF dev.device_type IS DISTINCT FROM 'Monitor'
       AND EXISTS (SELECT 1 FROM cied.implant_condition WHERE implant_pk = pk AND role = 'SOSPETTA') THEN
        RAISE EXCEPTION 'Impianto %: la patologia sospetta si indica solo per i loop recorder', pk;
    END IF;

    IF r.explant_date IS NOT NULL
       AND NOT EXISTS (SELECT 1 FROM cied.implant_condition WHERE implant_pk = pk AND role = 'DIAGNOSTICATA') THEN
        RAISE EXCEPTION 'Impianto %: all''espianto indicare le patologie diagnosticate', pk;
    END IF;

    IF r.explant_date IS NOT NULL AND r.switched_to_cied AND dev.device_type = 'Monitor'
       AND r.ilr_decisive IS NULL THEN
        RAISE EXCEPTION 'Impianto %: specificare se il loop recorder è stato determinante per il nuovo CIED', pk;
    END IF;

    IF dev.patient_pk IS NOT NULL AND dev.patient_pk <> r.patient_pk THEN
        RAISE EXCEPTION 'Impianto %: il dispositivo risulta associato a un altro paziente', pk;
    END IF;

    IF r.next_implant_pk IS NOT NULL AND
       (SELECT patient_pk FROM cied.implant WHERE implant_pk = r.next_implant_pk) <> r.patient_pk THEN
        RAISE EXCEPTION 'Impianto %: il CIED successivo deve appartenere allo stesso paziente', pk;
    END IF;
    RETURN NULL;
END $$;

DROP TRIGGER IF EXISTS trg_implant_check ON cied.implant;
CREATE CONSTRAINT TRIGGER trg_implant_check
    AFTER INSERT OR UPDATE ON cied.implant
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION cied.check_implant();

DROP TRIGGER IF EXISTS trg_implant_condition_check ON cied.implant_condition;
CREATE CONSTRAINT TRIGGER trg_implant_condition_check
    AFTER INSERT OR UPDATE OR DELETE ON cied.implant_condition
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION cied.check_implant();

