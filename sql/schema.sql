CREATE OR REPLACE VIEW cied.v_measurement AS
SELECT p.patient_pseudo, d.device_pseudo, d.model, s.session_dtm, s.session_type,
       o.branch, o.term, o.ieee_code, o.value_num, o.unit, o.period_start, o.period_end
FROM cied.observation o
JOIN cied.session s USING (session_pk)
JOIN cied.device  d USING (device_pk)
LEFT JOIN cied.patient p ON p.patient_pk = d.patient_pk
WHERE o.value_num IS NOT NULL;

CREATE OR REPLACE VIEW cied.v_episode AS
SELECT d.device_pseudo, s.session_dtm, o.branch, o.group_path,
       max(o.value_text) FILTER (WHERE o.name = 'TYPE')           AS episode_type,
       max(o.value_text) FILTER (WHERE o.name = 'VENDOR_TYPE')    AS vendor_type,
       max(o.value_num)  FILTER (WHERE o.name = 'RECENT_COUNT')   AS recent_count,
       min(o.period_start) FILTER (WHERE o.name = 'RECENT_COUNT') AS recent_start,
       max(o.period_end)   FILTER (WHERE o.name = 'RECENT_COUNT') AS recent_end,
       max(o.value_num)  FILTER (WHERE o.name = 'TOTAL_COUNT')    AS total_count
FROM cied.observation o
JOIN cied.session s USING (session_pk)
JOIN cied.device  d USING (device_pk)
WHERE o.section = 'IDC/STAT/EPISODE'
GROUP BY d.device_pseudo, s.session_dtm, o.branch, o.group_path;

CREATE OR REPLACE VIEW cied.v_zone AS
SELECT d.device_pseudo, s.session_dtm, o.group_path,
       max(o.value_text) FILTER (WHERE o.name = 'TYPE')        AS zone_type,
       max(o.value_text) FILTER (WHERE o.name = 'VENDOR_TYPE') AS vendor_type,
       max(o.value_text) FILTER (WHERE o.name = 'STATUS')      AS status,
       max(o.value_num)  FILTER (WHERE o.name = 'DETECTION_INTERVAL') AS detection_interval_ms
FROM cied.observation o
JOIN cied.session s USING (session_pk)
JOIN cied.device  d USING (device_pk)
WHERE o.section = 'IDC/SET/ZONE'
GROUP BY d.device_pseudo, s.session_dtm, o.group_path;

-- Impianti con le patologie aggregate per ruolo
CREATE OR REPLACE VIEW cied.v_implant AS
SELECT i.implant_pk, p.patient_pseudo, d.device_pseudo, d.device_type, d.model,
       i.implant_date, i.explant_date, er.label AS explant_reason, i.explant_reason_note,
       i.switched_to_cied, i.next_implant_pk, i.ilr_decisive,
       string_agg(c.code || ' ' || c.label, '; ' ORDER BY c.code) FILTER (WHERE ic.role = 'PREGRESSA')     AS pregresse,
       string_agg(c.code || ' ' || c.label, '; ' ORDER BY c.code) FILTER (WHERE ic.role = 'INDICAZIONE')   AS indicazioni,
       string_agg(c.code || ' ' || c.label, '; ' ORDER BY c.code) FILTER (WHERE ic.role = 'DIAGNOSTICATA') AS diagnosticate,
       i.nao_at_implant, p.nao_therapy AS nao_current,
       string_agg(c.code || ' ' || c.label, '; ' ORDER BY c.code) FILTER (WHERE ic.role = 'SOSPETTA')      AS sospette,
       -- età all'impianto in anni, dall'anno di nascita (cied conserva solo l'anno): ±1 anno
       extract(year FROM i.implant_date)::int - p.birth_year                                       AS age_at_implant
FROM cied.implant i
JOIN cied.patient p ON p.patient_pk = i.patient_pk
JOIN cied.device  d ON d.device_pk  = i.device_pk
LEFT JOIN cied.explant_reason er ON er.code = i.explant_reason_code
LEFT JOIN cied.implant_condition ic ON ic.implant_pk = i.implant_pk
LEFT JOIN cied.condition c ON c.condition_pk = ic.condition_pk
GROUP BY i.implant_pk, p.patient_pseudo, p.nao_therapy, p.birth_year, d.device_pseudo, d.device_type, d.model, er.label;

-- Esito dei loop recorder: hanno portato a un CIED terapeutico? In quanto tempo?
CREATE OR REPLACE VIEW cied.v_ilr_outcome AS
SELECT i.implant_pk                      AS ilr_implant_pk,
       p.patient_pseudo,
       d.model                           AS ilr_model,
       i.implant_date                    AS ilr_implant_date,
       i.explant_date                    AS ilr_explant_date,
       er.label                          AS explant_reason,
       i.switched_to_cied,
       i.ilr_decisive,
       nd.device_type                    AS next_device_type,
       ni.implant_date                   AS next_implant_date,
       ni.implant_date - i.implant_date  AS days_to_therapy,
       -- CIED terapeutici impiantati dopo il loop recorder, anche se non collegati esplicitamente
       (SELECT count(*) FROM cied.implant x JOIN cied.device xd ON xd.device_pk = x.device_pk
         WHERE x.patient_pk = i.patient_pk AND x.implant_date >= i.implant_date
           AND xd.device_type IS DISTINCT FROM 'Monitor') AS therapeutic_after_ilr,
       -- patologie sospette all'impianto del loop recorder
       (SELECT string_agg(c.code || ' ' || c.label, '; ' ORDER BY c.code)
          FROM cied.implant_condition ic JOIN cied.condition c USING (condition_pk)
         WHERE ic.implant_pk = i.implant_pk AND ic.role = 'SOSPETTA') AS sospette,
       -- il sospetto è stato confermato? true se almeno una patologia sospetta compare
       -- (stesso codice) tra le diagnosticate all'espianto; NULL se non c'erano sospetti
       -- o se il loop recorder non è ancora stato espiantato
       CASE WHEN i.explant_date IS NULL
                 OR NOT EXISTS (SELECT 1 FROM cied.implant_condition s
                                 WHERE s.implant_pk = i.implant_pk AND s.role = 'SOSPETTA')
            THEN NULL
            ELSE EXISTS (SELECT 1 FROM cied.implant_condition s
                           JOIN cied.implant_condition dg
                             ON dg.implant_pk = s.implant_pk AND dg.condition_pk = s.condition_pk
                            AND dg.role = 'DIAGNOSTICATA'
                          WHERE s.implant_pk = i.implant_pk AND s.role = 'SOSPETTA')
       END AS sospetto_confermato,
       -- età all'impianto del loop recorder, dall'anno di nascita: ±1 anno
       extract(year FROM i.implant_date)::int - p.birth_year AS age_at_implant,
       -- intervalli in giorni dall'impianto: si esportano al posto delle date precise
       COALESCE(i.explant_date, current_date) - i.implant_date AS days_monitored,
       (SELECT min(ic.first_diagnosis_date) FROM cied.implant_condition ic
         WHERE ic.implant_pk = i.implant_pk AND ic.role = 'DIAGNOSTICATA') - i.implant_date AS days_to_diagnosis
FROM cied.implant i
JOIN cied.device  d  ON d.device_pk  = i.device_pk
JOIN cied.patient p  ON p.patient_pk = i.patient_pk
LEFT JOIN cied.explant_reason er ON er.code = i.explant_reason_code
LEFT JOIN cied.implant ni ON ni.implant_pk = i.next_implant_pk
LEFT JOIN cied.device  nd ON nd.device_pk  = ni.device_pk
WHERE d.device_type = 'Monitor';

