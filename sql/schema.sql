-- =====================================================================
-- Schema della piattaforma CIED
--
--  vault  -> dati identificativi (anagrafica, seriale reale, XML grezzo)
--  cied   -> dati pseudonimizzati: misure, sessioni, storia clinica,
--            base per analisi ed export CSV
--
-- Collegamento tra i due schemi: gli pseudonimi patient_pseudo e
-- device_pseudo (HMAC-SHA256 con chiave segreta nel file .env).
--
-- Identità del paziente: codice progressivo interno vault.patient.patient_no
-- (non cambia mai). Gli ID esterni (Service Center, altri produttori...) sono
-- in vault.patient_identifier: un paziente può averne più d'uno.
-- Identità del dispositivo: produttore + modello + seriale.
--
-- Ruoli:
--   cied_analyst   -> legge solo lo schema cied (pseudonimizzato)
--   cied_clinician -> inserisce la storia clinica e legge il riepilogo
--                     identificato SOLO tramite vault.clinical_summary(),
--                     che registra ogni accesso in vault.access_log
-- =====================================================================

CREATE SCHEMA IF NOT EXISTS vault;
CREATE SCHEMA IF NOT EXISTS cied;

-- Estensioni (incluse in PostgreSQL): ricerca per somiglianza e rimozione degli accenti
CREATE EXTENSION IF NOT EXISTS pg_trgm  WITH SCHEMA public;
CREATE EXTENSION IF NOT EXISTS unaccent WITH SCHEMA public;

-- Testo normalizzato per la ricerca: minuscolo, senza accenti e apostrofi,
-- solo lettere e cifre separate da spazi. "D'Amico" -> "damico", "Delùca" -> "deluca".
CREATE OR REPLACE FUNCTION vault.norm(t text) RETURNS text
LANGUAGE sql IMMUTABLE PARALLEL SAFE AS $$
    SELECT btrim(regexp_replace(
               regexp_replace(lower(public.unaccent('public.unaccent'::regdictionary, coalesce(t, ''))),
                              '[''’`]', '', 'g'),
               '[^a-z0-9]+', ' ', 'g'))
$$;

-- =====================================================================
-- VAULT (identificativo)
-- =====================================================================
-- Anagrafica (MDC_ATTR_PT_*). Un paziente può avere più dispositivi nel tempo.
CREATE TABLE IF NOT EXISTS vault.patient (
    patient_no        bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 100001) PRIMARY KEY,
                                              -- codice paziente CIED: progressivo, non cambia mai
    patient_pseudo    text NOT NULL UNIQUE,   -- HMAC(patient_no): collegamento con lo schema cied
    name_family       text,
    name_given        text,
    birth_date        date,
    sex               text,
    attributes        jsonb NOT NULL DEFAULT '{}',   -- tutti i campi anagrafici ricevuti
    search_text       text NOT NULL DEFAULT '',      -- testo per la ricerca (aggiornato dai trigger)
    updated_at        timestamptz NOT NULL DEFAULT now()
);

-- ID esterni del paziente. Esempio: ('BIOTRONIK_HMSC', <clinica>, <ID nel Service Center>).
-- Se l'ID nel Service Center viene modificato, il nuovo si aggiunge come alias dello
-- stesso paziente (riconosciuto dal dispositivo), senza crearne uno nuovo.
CREATE TABLE IF NOT EXISTS vault.patient_identifier (
    system     text NOT NULL,
    namespace  text NOT NULL DEFAULT '',     -- es. CLINIC_ID del Service Center
    value      text NOT NULL,
    patient_no bigint NOT NULL REFERENCES vault.patient ON DELETE CASCADE,
    first_seen timestamptz NOT NULL DEFAULT now(),
    last_seen  timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (system, namespace, value)
);
CREATE INDEX IF NOT EXISTS ix_identifier_patient ON vault.patient_identifier (patient_no);

-- Il seriale da solo NON è univoco: lo è la terna produttore + modello + seriale.
CREATE TABLE IF NOT EXISTS vault.device_identity (
    device_pseudo  text PRIMARY KEY,
    patient_no     bigint REFERENCES vault.patient,
    manufacturer   text NOT NULL,
    model          text NOT NULL DEFAULT '',
    serial_number  text NOT NULL,
    hmsc_link      text,                      -- link alla scheda nel Service Center
    first_seen     timestamptz NOT NULL DEFAULT now(),
    UNIQUE (manufacturer, model, serial_number)
);
CREATE INDEX IF NOT EXISTS ix_device_identity_patient ON vault.device_identity (patient_no);
CREATE INDEX IF NOT EXISTS ix_device_identity_mfg_model ON vault.device_identity (manufacturer, model);

CREATE TABLE IF NOT EXISTS vault.export_raw (
    export_pk bigint PRIMARY KEY,             -- = cied.export.export_pk
    raw_xml   text NOT NULL
);

