CREATE TABLE IF NOT EXISTS cied.condition (
    condition_pk  serial PRIMARY KEY,
    coding_system text NOT NULL,              -- ICD-10-IM | ICD-9-CM | LOCAL
    code          text NOT NULL,
    label         text NOT NULL,
    UNIQUE (coding_system, code)
);

CREATE TABLE IF NOT EXISTS cied.explant_reason (
    code          text PRIMARY KEY,
    label         text NOT NULL
);

-- Un impianto = un dispositivo in un paziente, dalla data di impianto a
-- quella (eventuale) di espianto. Un paziente può avere più impianti nel tempo.
CREATE TABLE IF NOT EXISTS cied.implant (
    implant_pk          bigserial PRIMARY KEY,
    patient_pk          bigint NOT NULL REFERENCES cied.patient,
    device_pk           bigint NOT NULL UNIQUE REFERENCES cied.device,
    implant_date        date NOT NULL,
    -- campi dell'espianto (facoltativi finché il dispositivo è impiantato)
    explant_date        date,
    explant_reason_code text REFERENCES cied.explant_reason,
    explant_reason_note text,
    switched_to_cied    boolean,              -- si è passati a un altro CIED?
    next_implant_pk     bigint REFERENCES cied.implant,  -- quale (se registrato)
    ilr_decisive        boolean,              -- il loop recorder è stato determinante?
    nao_at_implant      boolean NOT NULL,     -- terapia NAO al momento dell'impianto (obbligatoria)
    notes               text,
    created_at          timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT chk_explant_after_implant
        CHECK (explant_date IS NULL OR explant_date >= implant_date),
    -- con data di espianto: motivazione e "passaggio ad altro CIED" obbligatori;
    -- senza data di espianto: tutti i campi dell'espianto devono restare vuoti
    CONSTRAINT chk_explant_fields CHECK (
        (explant_date IS NULL AND explant_reason_code IS NULL AND explant_reason_note IS NULL
             AND switched_to_cied IS NULL AND next_implant_pk IS NULL AND ilr_decisive IS NULL)
        OR
        (explant_date IS NOT NULL AND explant_reason_code IS NOT NULL AND switched_to_cied IS NOT NULL)
    ),
    CONSTRAINT chk_other_reason_note
        CHECK (explant_reason_code IS DISTINCT FROM 'OTHER' OR explant_reason_note IS NOT NULL),
    CONSTRAINT chk_next_implant
        CHECK (next_implant_pk IS NULL OR (switched_to_cied AND next_implant_pk <> implant_pk)),
    CONSTRAINT chk_ilr_decisive
        CHECK (ilr_decisive IS NULL OR switched_to_cied)
);

-- Più patologie per impianto: una riga per patologia (tabella di associazione).
--   PREGRESSA     -> anamnesi al momento dell'impianto        (obbligatoria)
--   INDICAZIONE   -> patologia/evento che ha motivato l'impianto (obbligatoria)
--   SOSPETTA      -> patologia sospetta che il loop recorder deve confermare o escludere
--                    (facoltativa, solo per i loop recorder)
--   DIAGNOSTICATA -> diagnosticata durante il periodo di impianto (obbligatoria all'espianto)
CREATE TABLE IF NOT EXISTS cied.implant_condition (
    implant_pk           bigint NOT NULL REFERENCES cied.implant ON DELETE CASCADE,
    condition_pk         integer NOT NULL REFERENCES cied.condition,
    role                 text NOT NULL,       -- valori ammessi: vincolo implant_condition_role_check
    first_diagnosis_date date,                -- data della prima diagnosi (facoltativa, solo DIAGNOSTICATA)
    note                 text,
    PRIMARY KEY (implant_pk, condition_pk, role),
    CHECK (first_diagnosis_date IS NULL OR first_diagnosis_date <= current_date)
);
-- Ruoli ammessi. Il vincolo viene ricreato a ogni init_db, così anche i database
-- creati prima dell'aggiunta di SOSPETTA (24/11/2026) si aggiornano da soli.
ALTER TABLE cied.implant_condition DROP CONSTRAINT IF EXISTS implant_condition_role_check;
ALTER TABLE cied.implant_condition ADD CONSTRAINT implant_condition_role_check
    CHECK (role IN ('PREGRESSA', 'INDICAZIONE', 'SOSPETTA', 'DIAGNOSTICATA'));

-- La data della prima diagnosi si indica solo per le patologie DIAGNOSTICATA (24/11/2026).
-- Il vincolo vale subito per i nuovi inserimenti; le righe già presenti vengono
-- controllate a parte, così un vecchio dato non blocca l'aggiornamento del database.
ALTER TABLE cied.implant_condition DROP CONSTRAINT IF EXISTS chk_first_diagnosis_only_diagnosticata;
ALTER TABLE cied.implant_condition ADD CONSTRAINT chk_first_diagnosis_only_diagnosticata
    CHECK (first_diagnosis_date IS NULL OR role = 'DIAGNOSTICATA') NOT VALID;
DO $$
BEGIN
    ALTER TABLE cied.implant_condition VALIDATE CONSTRAINT chk_first_diagnosis_only_diagnosticata;
EXCEPTION WHEN check_violation THEN
    RAISE WARNING 'Ci sono patologie non DIAGNOSTICATA con la data della prima diagnosi. '
                  'Per vederle: SELECT * FROM cied.implant_condition '
                  'WHERE first_diagnosis_date IS NOT NULL AND role <> ''DIAGNOSTICATA'';';
END $$;

